"""The finished clothes rack on Newton: does it stand, and how hard a push tips it?

The assembled rack is one rigid body (the bolted clamps do not slip: design.checks gives
the grip) with its real mass, centre of mass and inertia from design.mass_properties,
clothes included, standing on its four feet on a concrete floor. The director,
clothes_rack_load_test, lets it settle, then pushes the bar with a slowly rising force,
front to back and then sideways, and reports the force at which the feet on the far side
lift, against the hand calculation.

    python projects/manufacturing/products/clothes_rack/load_test.py [--load-kg 20]

writes projects/samples/demos/worlds/manufacturing/clothes_rack_load_test.omniworld.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import assembly  # noqa: E402
import design  # noqa: E402

WORLD = design.ROOT / "projects/samples/demos/worlds/manufacturing/clothes_rack_load_test.omniworld"
FLOOR_MU = 0.6          # rubber glide on sealed concrete, a common handbook figure (0.6-0.8)
_f = assembly._f


def world(rack: design.Rack, load_kg: float, out: Path) -> str:
    p = assembly.plan(rack)
    shapes = p.pop("_shapes")
    mesh_url = Path(os.path.relpath(assembly.MESH, out.parent)).as_posix()
    mp = design.mass_properties(rack, load_kg)
    I = mp["inertia_kg_m2"]
    checks = design.checks(rack, load_kg)
    # Everything where the assembly leaves it, under one body.
    kids = []
    for name, track in p["parts"].items():
        if name.startswith("garment") and load_kg <= 0:
            continue
        k = track[-1]
        rot = assembly.axis_angle(k[4:8])
        kids.append(f"Pose {{ translation {_f(k[1])} {_f(k[2])} {_f(k[3])} rotation {' '.join(_f(v) for v in rot)} "
                    f"children [ {shapes[name].replace('MESH', mesh_url)} ] }}")
    feet = " ".join(f"Pose {{ translation {_f(sx * rack.upright_x_mm / 1000)} {_f(sy * rack.foot_y_mm / 1000)} 0.004 "
                    f"children [ Box {{ size 0.03 0.03 0.008 }} ] }}" for sx in (-1, 1) for sy in (-1, 1))
    expect = {"front_n": checks["tip_force_at_bar_n"],
              # Pushed toward +X it pivots on the right-hand feet: the arm is from them to the CoM.
              "side_n": round(mp["mass_kg"] * 9.81 * (rack.upright_x_mm / 1000 - mp["com_m"][0])
                              / (rack.bar_z / 1000), 1),
              "slide_n": round(FLOOR_MU * mp["mass_kg"] * 9.81, 1)}
    args = {"push_z": round(rack.bar_z / 1000, 4), "feet": [[sx * rack.upright_x_mm / 1000, sy * rack.foot_y_mm / 1000]
                                                            for sx in (-1, 1) for sy in (-1, 1)],
            "expect": expect, "mass_kg": round(mp["mass_kg"], 3), "load_kg": load_kg}
    lines = ["#OMNISIM R2025a utf8",
             'EXTERNPROTO "omnisim://projects/objects/backgrounds/protos/OmniSimSky.proto"',
             'EXTERNPROTO "omnisim://projects/objects/lights/protos/OmniSimSun.proto"',
             'EXTERNPROTO "omnisim://projects/objects/lights/protos/OmniSimSunMarker.proto"',
             "# Generated by projects/manufacturing/products/clothes_rack/load_test.py. Regenerate; do not hand-edit.",
             f'WorldInfo {{ basicTimeStep 4 title "Clothes rack - load test" FPS 30 newtonSolver "mujoco" '
             f'newtonGroundMu {_f(FLOOR_MU)} newtonCone "elliptic" newtonImpratio 10 }}',
             f"DEF VIEW Viewpoint {{ position 2.6 -3.4 1.5 orientation "
             f"{' '.join(_f(v) for v in assembly.look([2.6, -3.4, 1.5], [0, 0, 0.75]))} fieldOfView .75 }}",
             "OmniSimSky { }", "DEF SUN OmniSimSun { }", "DEF SUN_MARKER OmniSimSunMarker { translation 5 -7 9 }",
             'DEF FLOOR Solid { name "floor" translation 0 0 -.05 children [ Shape { appearance PBRAppearance '
             '{ baseColor .3 .31 .32 roughness .9 metalness 0 } geometry Box { size 8 8 .1 } } ] boundingObject Box '
             '{ size 8 8 .1 } }',
             f'DEF RACK Solid {{ name "clothes rack" translation 0 0 0.001\n  children [\n    '
             + "\n    ".join(kids) + "\n  ]\n"
             f"  boundingObject Group {{ children [ {feet} ] }}\n"
             f"  physics Physics {{ density -1 mass {_f(mp['mass_kg'])} centerOfMass [ "
             f"{' '.join(_f(v) for v in mp['com_m'])} ] inertiaMatrix [ {_f(I[0][0])} {_f(I[1][1])} {_f(I[2][2])}, "
             f"{_f(I[0][1])} {_f(I[0][2])} {_f(I[1][2])} ] }}\n}}",
             # The push, drawn: an arrow at the bar that the director shows while it pushes.
             'DEF PUSH Pose { translation 0 0 -5 children [ Pose { translation 0 0 0.15 children [ Shape { appearance '
             'PBRAppearance { baseColor .9 .15 .1 roughness .5 metalness 0 } geometry Cylinder { radius 0.008 height 0.3 } } ] } '
             'Pose { translation 0 0 0.33 children [ Shape { appearance PBRAppearance { baseColor .9 .15 .1 roughness .5 '
             'metalness 0 } geometry Cone { bottomRadius 0.022 height 0.06 } } ] } ] }',
             f'DEF DIRECTOR Robot {{ name "load-test-director" controller "clothes_rack_load_test" '
             f"controllerArgs [ \"--test\" {json.dumps(json.dumps(args))} ] supervisor TRUE }}"]
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--load-kg", type=float, default=20.0)
    ap.add_argument("--out", type=Path, default=WORLD)
    args = ap.parse_args(argv)
    rack = design.Rack()
    if not assembly.MESH.exists():
        design.write_half_stl(rack, assembly.MESH, res=1.0, metres=True, frame="connector")
    args.out.write_text(world(rack, args.load_kg, args.out), encoding="utf-8", newline="\n")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
