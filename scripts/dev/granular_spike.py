"""Granular-physics measurement spike — companion to
docs/developer/granular-physics-plan.md.

Generates granular_sand_demo variants at parametric sphere counts,
runs each headless with --log-performance=<file>, parses the resulting
performance log, and emits a comparison table.

The goal is to confirm or refute the plan's diagnosis before any code
lands: where is wall-clock time *actually* being spent during the
active phase of a granular pile? Physics? Rendering? Loading?

Usage:

    python scripts/dev/granular_spike.py
        # default sweep: N = 100, 200, 400, 600 spheres, 15 s of sim each

    python scripts/dev/granular_spike.py --counts 200 600 1000 --duration 20

The script writes:
  - one .wbt per sweep value under tests/granular-spike/worlds/
  - one .perf log per sweep value under tests/granular-spike/logs/
  - one Markdown summary at tests/granular-spike/results.md
"""

from __future__ import annotations

import argparse
import math
import os
import random
import re
import subprocess
import sys
import time
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
SPIKE_DIR = REPO_ROOT / "tests" / "granular-spike"
WORLDS_DIR = SPIKE_DIR / "worlds"
LOGS_DIR = SPIKE_DIR / "logs"

R = 0.05
SPACING = 0.105
PIT_HALF = 1.4
WALL_H = 1.0
WALL_T = 0.15

