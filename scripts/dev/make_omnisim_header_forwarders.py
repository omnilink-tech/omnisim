"""Phase I of the Webots->OmniSim rebrand — webots/*.h are deprecation shims.

Canonical public C / C++ controller headers live under

    include/controller/c/omnisim/...
    include/controller/cpp/omnisim/...

This script mirrors every one as a one-line forwarder under the legacy
``webots/`` path so external controllers that still write::

    #include <webots/robot.h>
    #include <webots/Robot.hpp>

keep compiling. New code should use ``<omnisim/...>`` directly.

Idempotent: regenerate the entire shim tree on every run.
"""

from __future__ import annotations

import sys
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parents[2]
LANG_DIRS = (
    ("c", "include/controller/c"),
    ("cpp", "include/controller/cpp"),
)


# These shims REPLACE the upstream Webots headers in place (git tracks them as a
# modification of the original path, not as new files), so Apache-2.0 §4(c) requires
# us to keep Cyberbotics' copyright notice on them and §4(b) requires the
# modification notice. Emit both here, or a regeneration silently strips them and
# tests/sources/test_license.py goes red. See docs/developer/copyright-headers.md.
