# cube's TOP face from directly above, so dense packing / rolling / jaw geometry
# stop mattering -- the pile empties top-down with no shaking. A top-down camera
# (Recognition node) detects the cubes; its controller publishes the visible
# cube ids+colours to customData, and the arm picks the cubes the camera sees
# (occlusion => the top of the pile), reading each cube's pose from the scene.
#
# Newton + MuJoCo solver (friction grasp). Bin + tray walls are real Newton
# static colliders (launch with OMNISIM_NEWTON_STATICS=1) so the gripper can't
