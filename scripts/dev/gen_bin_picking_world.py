cols = [0.34, 0.42, 0.50, 0.58]
rows = [-0.08, 0.0, 0.08]
zs = [0.05, 0.115, 0.18]
cells = [(x, y, z) for z in zs for y in rows for x in cols]   # 36
colors = ['red'] * 18 + ['blue'] * 18
random.shuffle(colors)


def rrot():
    ax = [random.uniform(-1, 1) for _ in range(3)]
    n = sum(a * a for a in ax) ** 0.5 or 1.0
    ax = [a / n for a in ax]
    ang = random.uniform(0.05, 0.22)
    return "%.3f %.3f %.3f %.3f" % (ax[0], ax[1], ax[2], ang)


parts = []
for i, (cx, cy, cz) in enumerate(cells, start=1):
    x = cx + random.uniform(-0.008, 0.008)
    y = cy + random.uniform(-0.008, 0.008)
    r, g, b = (RED if colors[i - 1] == 'red' else BLUE)
    parts.append(
        'DEF PART_%d Solid { translation %.4f %.4f %.3f rotation %s physicsBackend "newton" '
        'children [ DEF PART_%d_SHAPE Shape { appearance PBRAppearance { baseColor %s %s %s roughness 1 metalness 0 } '
        'geometry Box { size 0.05 0.05 0.05 } } ] name "part_%d" boundingObject USE PART_%d_SHAPE '
        'recognitionColors [ %s %s %s ] physics Physics { density -1 mass 0.06 } }'
        % (i, x, y, cz, rrot(), i, r, g, b, i, i, r, g, b))

out = HEADER + "\n".join(parts) + "\n"
path = "projects/samples/demos/worlds/flagship/omniarm6_bin_picking.omniworld"
open(path, "w", encoding="utf-8", newline="\n").write(out)
print("wrote %s : 36 cubes (%d red / %d blue)" % (path, colors.count('red'), colors.count('blue')))
