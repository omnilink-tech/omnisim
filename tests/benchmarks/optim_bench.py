BENCH_SUPERVISOR = """
Robot {{
  name "bench_supervisor"
  controller "bench_quit"
  controllerArgs [{controller_args}]
  supervisor TRUE
}}
"""


def bench_supervisor_block(steps: int, extra_args=()) -> str:
    """The quit-after-N-steps supervisor node. Use this, never .format() by hand.

    THREE of the four call sites did format it by hand, as
    ``BENCH_SUPERVISOR.format(steps=steps)`` -- but the template's only field is
    ``{controller_args}``, so ``gen_many_cameras``, ``gen_noisy_robots`` and
    ``gen_chunky_robots`` each raised ``KeyError: 'controller_args'`` and could
    not generate a world AT ALL. It went unnoticed because nothing in this tree
    ever called them; the field was renamed in 323395c95 and only
    ``gen_many_robots`` was updated. Gated now by
    tests/benchmarks/test_bench_world_generators.py.
    """
    args = ["--steps", str(steps), *extra_args]
    return BENCH_SUPERVISOR.format(
        controller_args=" ".join(f'"{a}"' for a in args))


def gen_many_robots(robots: int, steps: int, backend: Optional[str] = None,
                    state_out: Optional[Path] = None) -> Path:
    """N omnibots + 1 supervisor that quits after `steps`.

    Historical note: the generated world requests ``omnibot_random``, but
    controller lookup is relative to this benchmark project and that controller
    is not present here. OmniSim therefore runs its built-in empty ``<generic>``
    fallback. The name is retained so existing baselines remain comparable;
    do not interpret this scenario as 50 active random-walk Python controllers.

    `backend` sets the per-robot `physicsBackend` field ("newton" / "auto").
    None leaves it unset, i.e. the schema default `auto` (Solid.wrl / Robot.wrl).

    "ode" IS REFUSED (2026-08-08): src/ode was DELETED (commit bdc02139). This
    used to be "the apples-to-apples ODE-vs-Newton lever: same robots, same
    arena, same controllers, only the solver changes", and it no longer is.

    Unlike the retired ENV knobs (which the engine now simply ignores), the
    per-Solid FIELD is still honoured -- so this one really would generate a
    world full of bodies that never move, and the engine says so itself. Verified
    2026-08-08 with a two-ball probe, one pinned and one not:

        WARNING: DEF BALL_PINNED Solid: This Solid asks for physicsBackend "ode",
        which no longer selects a physics engine: ODE was removed and Newton is
        the only backend. The node will have NO gravity and NO contact -- it is a
        visual-only body. Delete the field to simulate it with Newton.
        INFO: [OmNewtonBackend] registered 1 dynamic + 1 static Newton bodies

    One dynamic body registered, not two: the pinned ball got none. A world of
    those would not read as an error, it would read as a spectacularly fast
    benchmark -- and a throughput number from a frozen scene is the most
    dangerous kind of wrong.
    """
    arena = max(8, int(robots ** 0.5) * 2)
    body = WORLD_HEADER.format(time_step=16, title=f"bench_many_robots_{robots}",
                               arena=arena)
    extra_args = []
    if state_out:
        extra_args = ["--state-out", state_out.resolve().as_posix(),
                      "--robot-count", str(robots)]
    body += bench_supervisor_block(steps, extra_args)
    side = max(1, int(robots ** 0.5))
    spacing = arena * 0.8 / max(side, 1)
    half = arena * 0.4
    if backend == "ode":
        raise ValueError(
            'backend "ode" is not available: src/ode was DELETED (commit '
            "bdc02139) and Newton is the only physics backend. A world pinned "
            "to it does not simulate, so any throughput number from it is void.")
    backend_line = f'  physicsBackend "{backend}"\n' if backend else ""
    for i in range(robots):
        row, col = divmod(i, side)
        x = -half + col * spacing
        y = -half + row * spacing
        body += (
            f'\nDEF BOT_{i:03d} URDFRobot {{\n'
            f'  url "{OMNIBOT_URDF.as_posix()}"\n'
            f'  translation {x:.3f} {y:.3f} 0.04\n'
            f'  name "omnibot_{i:03d}"\n'
            f'  controller "omnibot_random"\n'
            f'{backend_line}'
            f'}}\n'
        )
    suffix = f"_{backend}" if backend else ""
    out = WORLDS_DIR / f"many_robots_{robots:03d}{suffix}.omniworld"
    out.write_text(body, encoding="utf-8")
    return out


def gen_many_cameras(cameras: int, steps: int, depth: bool = False,
                     width: int = 320, height: int = 240) -> Path:
    """N camera-bearing static robots arranged in a circle around a stack of
    boxes (so there's something to render)."""
    import math
    arena = 12
    body = WORLD_HEADER.format(time_step=16, title=f"bench_many_cameras_{cameras}",
                               arena=arena)
    body += bench_supervisor_block(steps)
    # Some boxes in the middle so cameras have content to render.
    for i in range(8):
        body += (
            f'\nSolid {{\n'
            f'  translation {(i % 4) * 0.8 - 1.2:.2f} {(i // 4) * 0.8 - 0.4:.2f} 0.4\n'
            f'  name "box_{i}"\n'
            f'  children [\n'
            f'    Shape {{\n'
            f'      appearance PBRAppearance {{ baseColor 0.7 0.4 0.3 roughness 0.6 metalness 0 }}\n'
            f'      geometry Box {{ size 0.4 0.4 0.8 }}\n'
            f'    }}\n'
            f'  ]\n'
            f'  boundingObject Box {{ size 0.4 0.4 0.8 }}\n'
            f'}}\n'
        )
    # Cameras in a ring looking inward.
    radius = arena * 0.4
    for i in range(cameras):
        ang = 2 * math.pi * i / max(cameras, 1)
        x = radius * math.cos(ang)
        y = radius * math.sin(ang)
        # Yaw the robot so its +X (camera default forward) points toward origin.
        yaw = math.atan2(-y, -x)
        children = [
            'Camera {\n'
            f'      name "front_camera"\n'
            f'      width {width}\n'
            f'      height {height}\n'
            f'      fieldOfView 1.4\n'
            f'    }}'
        ]
        if depth:
            children.append(
                'RangeFinder {\n'
                f'      name "front_depth"\n'
                f'      width {width}\n'
                f'      height {height}\n'
                f'      fieldOfView 1.4\n'
                f'    }}'
            )
        body += (
            f'\nRobot {{\n'
            f'  name "cam_{i:03d}"\n'
            f'  translation {x:.3f} {y:.3f} 0.5\n'
            f'  rotation 0 0 1 {yaw:.4f}\n'
            f'  controller "bench_camera"\n'
            f'  children [\n'
            f'    {chr(10).join(children)}\n'
            f'    Shape {{\n'
            f'      appearance PBRAppearance {{ baseColor 0.2 0.6 1.0 roughness 0.4 metalness 0 }}\n'
            f'      geometry Sphere {{ radius 0.05 }}\n'
            f'    }}\n'
            f'  ]\n'
            f'}}\n'
        )
    suffix = "_depth" if depth else ""
    out = WORLDS_DIR / f"many_cameras_{cameras:03d}{suffix}.omniworld"
    out.write_text(body, encoding="utf-8")
    return out


