"""Targeted benchmarks for the multi-instance + many-robot optimization plan.

Scenarios:

  many-robots     — N robots in one world, measure step + IPC cost.
  many-cameras    — N cameras in one world, measure render + GPU-transfer cost.
  multi-instance  — K parallel headless processes against one fixed world,
                    measure aggregate physics throughput and per-instance
                    log-file collisions.
  all             — run all of the above.

Each scenario generates a `.wbt` under `tests/benchmarks/optim/worlds/`,
launches `omnisim-bin` with `--log-performance`, parses the log, and
emits a JSON record. `compare` diffs two JSON outputs.

The plan this serves: docs/developer/multi-instance-optimization-plan.md
"""

