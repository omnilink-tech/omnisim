def _record_key(r: PerfRecord) -> tuple:
    return (r.scenario, json.dumps(r.params, sort_keys=True))


def _aggregate_repeats(group: list[PerfRecord]) -> PerfRecord:
    """Merge N runs of the same (scenario, params) into one record. Numeric
    fields in avg/devices/controllers become the median across runs; min/max/
    stdev are stored alongside as `<field>_min`, `<field>_max`, `<field>_stdev`.
    """
    base = group[0]
    out = PerfRecord(
        scenario=base.scenario,
        params=dict(base.params),
        log_path=f"(median of {len(group)} runs)",
        wall_time_s=round(statistics.median([r.wall_time_s for r in group]), 3),
        returncode=max(r.returncode for r in group),
    )
    out.steps_count = base.steps_count
    out.threads_count = base.threads_count

    import math
    for field_name in ("avg", "devices", "controllers"):
        keys: set[str] = set()
        for r in group:
            keys.update(getattr(r, field_name).keys())
        merged: dict = {}
        for key in keys:
            vals = []
            for r in group:
                v = getattr(r, field_name).get(key)
                # Drop NaN/inf — e.g. trianglesCount under --no-rendering is NaN.
                if isinstance(v, (int, float)) and not (isinstance(v, float) and not math.isfinite(v)):
                    vals.append(float(v))
            if not vals:
                continue
            merged[key] = round(statistics.median(vals), 4)
            if len(vals) >= 2:
                merged[f"{key}_min"] = round(min(vals), 4)
                merged[f"{key}_max"] = round(max(vals), 4)
                merged[f"{key}_stdev"] = round(statistics.stdev(vals), 4)
        setattr(out, field_name, merged)

    out.notes.append(f"aggregated from {len(group)} runs (median)")
    out.notes.append(f"per-run wall_time_s: {[r.wall_time_s for r in group]}")
    out.notes.append(f"per-run returncode: {[r.returncode for r in group]}")
    return out


def with_repeats(fn: Callable, args, repeats: int) -> list[PerfRecord]:
    """Run `fn(args)` `repeats` times and aggregate. With `repeats >= 2` the
    FIRST run is treated as a cache warm-up and excluded from the aggregate
    (it is still kept in the raw output for inspection). This matches the
    "pass1 = warm-up, pass2 = measurement" protocol documented in the plan.

    Returns one aggregated record per (scenario, params) group plus all raw
    individual records (including the discarded warm-up).
    """
    if repeats <= 1:
        return fn(args)

    raw: list[PerfRecord] = []
    for i in range(repeats):
        tag = "warm-up (discarded)" if i == 0 else f"measurement {i}/{repeats - 1}"
        print(f"\n[bench] === repeat {i + 1}/{repeats}: {tag} ===")
        runs = fn(args)
        for r in runs:
            if i == 0:
                r.notes.append("warm-up run; excluded from aggregate")
        raw.extend(runs)

    # Group only the measurement runs (skip the first repeat).
    measurement_runs_per_repeat = len(raw) // repeats
    measurement_only = raw[measurement_runs_per_repeat:]
    groups: dict[tuple, list[PerfRecord]] = {}
    for r in measurement_only:
        groups.setdefault(_record_key(r), []).append(r)

    aggregated: list[PerfRecord] = []
    for key, recs in groups.items():
        if len(recs) >= 2:
            aggregated.append(_aggregate_repeats(recs))
        else:
            aggregated.append(recs[0])
    return aggregated + raw


