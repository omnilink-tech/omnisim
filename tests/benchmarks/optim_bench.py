# --- perf log parsing ---------------------------------------------------

@dataclass
class PerfRecord:
    scenario: str
    params: dict
    log_path: str
    wall_time_s: float
    returncode: int
    avg: dict = field(default_factory=dict)
    tot: dict = field(default_factory=dict)
    devices: dict = field(default_factory=dict)
    controllers: dict = field(default_factory=dict)
    steps_count: int = 0
    threads_count: Optional[int] = None
    notes: list = field(default_factory=list)


def parse_perf_log(path: Path) -> dict:
    """Parse the OmPerformanceLog format. Returns headers + AVG/TOT rows.

    Layout (per OmPerformanceLog.cpp):

        World: ...
        World metrics: ...
        Threads count: N
        ...
        <mode> <stepsCount> <loading(ms)> ... <controller:NAME(ms)>
        AVG  <count> <values...>
        TOT  <count> <values...>
    """
    if not path.exists():
        return {"error": f"no log at {path}"}
    text = path.read_text(errors="replace")

    headers: list[str] = []
    avg_row: list[str] = []
    tot_row: list[str] = []
    threads = None

    lines = [ln.rstrip() for ln in text.splitlines()]
    for i, line in enumerate(lines):
        if line.startswith("Threads count:"):
            try:
                threads = int(line.split(":", 1)[1].strip())
            except ValueError:
                pass
        if line.startswith("<mode>"):
            headers = line.split()
            # next two non-empty lines are AVG and TOT
            for j in range(i + 1, len(lines)):
                cells = lines[j].split()
                if not cells:
                    continue
                if cells[0] == "AVG":
                    avg_row = cells
                elif cells[0] == "TOT":
                    tot_row = cells
                    break

    def to_dict(row: list[str]) -> dict:
        if not row or len(row) < 3:
            return {}
        out = {"_steps": int(row[1])}
        for header, val in zip(headers[2:], row[2:]):
            try:
                out[header.strip("<>")] = float(val)
            except ValueError:
                out[header.strip("<>")] = val
        return out

    avg = to_dict(avg_row)
    tot = to_dict(tot_row)

    devices = {k: v for k, v in avg.items() if k.startswith("device:")}
    controllers = {k: v for k, v in avg.items() if k.startswith("controller:")}

    return {
        "headers": headers,
        "avg": avg,
        "tot": tot,
        "devices": devices,
        "controllers": controllers,
        "threads_count": threads,
        "steps_count": avg.get("_steps", 0),
    }


# --- runner --------------------------------------------------------------

def webots_cmd(world: Path, perf_log: Path, port: Optional[int] = None,
               forward_stdio: bool = True) -> list[str]:
    binary = find_binary()
    cmd = [
        str(binary),
        str(world),
        "--batch",
        "--mode=fast",
        "--no-rendering",
        "--minimize",
        f"--log-performance={perf_log}",
    ]
    # `--stdout`/`--stderr` make the simulator re-emit controller output on its
    # own stdout/stderr. Bench scenarios that intentionally generate volumes
    # of controller output (e.g. `noisy`) would flood the subprocess PIPE
    # buffer; those callers pass forward_stdio=False.
    if forward_stdio:
        cmd += ["--stdout", "--stderr"]
    if port is not None:
        cmd.append(f"--port={port}")
    return cmd


def _sample_peak_rss(pid: int, sample_interval_s: float = 0.25) -> dict:
    """Background thread body: samples the target process tree's RSS until the
    process exits, returns peak. Returns {"peak_rss_bytes": int, "samples": int}.
    Best-effort: returns zeros if psutil missing or the process vanishes."""
    out = {"peak_rss_bytes": 0, "samples": 0}
    try:
        import psutil  # noqa: F401
    except ImportError:
        return out
    import psutil
    try:
        p = psutil.Process(pid)
    except psutil.NoSuchProcess:
        return out
    peak = 0
    samples = 0
    while True:
        try:
            if not p.is_running():
                break
            total = 0
            try:
                total += p.memory_info().rss
            except (psutil.NoSuchProcess, psutil.AccessDenied):
                break
            for c in p.children(recursive=True):
                try:
                    total += c.memory_info().rss
                except (psutil.NoSuchProcess, psutil.AccessDenied):
                    pass
            if total > peak:
                peak = total
            samples += 1
        except psutil.NoSuchProcess:
            break
        time.sleep(sample_interval_s)
    out["peak_rss_bytes"] = peak
    out["samples"] = samples
    return out


def run_world(world: Path, scenario: str, params: dict,
              tag: str, port: Optional[int] = None,
              timeout: int = 600,
              omnisim_log_path: Optional[Path] = None,
              forward_stdio: bool = True) -> PerfRecord:
    LOG_DIR.mkdir(exist_ok=True, parents=True)
    perf_log = LOG_DIR / f"{tag}.log"
    if perf_log.exists():
        perf_log.unlink()

    env = os.environ.copy()
    env["OMNISIM_HOME"] = str(REPO_ROOT)
    binary = find_binary()
    if sys.platform == "win32":
        env["PATH"] = str(binary.parent) + os.pathsep + env.get("PATH", "")
    if omnisim_log_path is not None:
        env["OMNISIM_LOG_PATH"] = str(omnisim_log_path)

    cmd = webots_cmd(world, perf_log, port=port, forward_stdio=forward_stdio)
    print(f"[bench] {tag}: {' '.join(str(c) for c in cmd)}", flush=True)
    t0 = time.time()
    proc = subprocess.Popen(
        cmd,
        env=env,
        cwd=REPO_ROOT,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
    )
    # Sample RSS in a background thread until the process exits.
    import threading
    rss_result = {"peak_rss_bytes": 0, "samples": 0}
    def _sampler():
        rss_result.update(_sample_peak_rss(proc.pid))
    sampler_thread = threading.Thread(target=_sampler, daemon=True)
    sampler_thread.start()
    try:
        stdout, stderr = proc.communicate(timeout=timeout)
    except subprocess.TimeoutExpired:
        proc.kill()
        stdout, stderr = proc.communicate()
    sampler_thread.join(timeout=2.0)
    wall = time.time() - t0
    parsed = parse_perf_log(perf_log)
    rec = PerfRecord(
        scenario=scenario,
        params=params,
        log_path=str(perf_log.relative_to(REPO_ROOT)),
        wall_time_s=round(wall, 3),
        returncode=proc.returncode,
    )
    if "error" in parsed:
        rec.notes.append(parsed["error"])
        rec.notes.append(f"stdout-tail: {stdout.decode(errors='replace')[-400:]}")
        rec.notes.append(f"stderr-tail: {stderr.decode(errors='replace')[-400:]}")
    else:
        rec.avg = parsed["avg"]
        rec.tot = parsed["tot"]
        rec.devices = parsed["devices"]
        rec.controllers = parsed["controllers"]
        rec.steps_count = parsed["steps_count"]
        rec.threads_count = parsed["threads_count"]
    # Surface peak RSS in MB so it shows up in `compare` alongside the perf
    # buckets. 0.0 means psutil unavailable or process vanished too quickly.
    rec.avg["peak_rss_mb"] = round(rss_result["peak_rss_bytes"] / 1024 / 1024, 2)
    return rec


# --- scenarios -----------------------------------------------------------

def bench_many_robots(sizes: list[int], steps: int,
                      backend: Optional[str] = None,
                      state_out: Optional[Path] = None) -> list[PerfRecord]:
    out = []
    suffix = f"-{backend}" if backend else ""
    for n in sizes:
        snapshot = state_out if len(sizes) == 1 else None
        world = gen_many_robots(robots=n, steps=steps, backend=backend,
                                state_out=snapshot)
        params = {"robots": n, "steps": steps}
        if backend:
            params["backend"] = backend
        out.append(run_world(world, "many-robots", params,
                             tag=f"many-robots-{n:03d}{suffix}"))
    return out


def bench_many_cameras(sizes: list[int], steps: int, depth: bool = False) -> list[PerfRecord]:
    out = []
    for n in sizes:
        world = gen_many_cameras(cameras=n, steps=steps, depth=depth)
        out.append(run_world(world, "many-cameras",
                             {"cameras": n, "steps": steps, "depth": depth},
                             tag=f"many-cameras-{n:03d}{'-depth' if depth else ''}"))
    return out


def bench_chunky_controllers(robots: int, byte_sizes: list[int], steps: int) -> list[PerfRecord]:
    """For each byte_size, run a world with `robots` chunky controllers (large
    customData + sensor reads) and measure the controller bucket time. Targets
    the simulator-side IPC reader (item 4) and writer (item 5) cost paths."""
    out = []
    for n in byte_sizes:
        world = gen_chunky_robots(robots=robots, bytes_per_step=n, steps=steps)
        out.append(run_world(world, "chunky-controllers",
                             {"robots": robots, "bytes_per_step": n, "steps": steps},
                             tag=f"chunky-r{robots:02d}-b{n:06d}"))
    return out


def bench_noisy_controllers(robots: int, byte_sizes: list[int], steps: int) -> list[PerfRecord]:
    """For each byte_size, run a world with `robots` chatty controllers and
    measure the controller bucket time. The bench discards forwarded stdio
    so the subprocess PIPE doesn't fill — see webots_cmd."""
    out = []
    for n in byte_sizes:
        world = gen_noisy_robots(robots=robots, bytes_per_step=n, steps=steps)
        out.append(run_world(world, "noisy-controllers",
                             {"robots": robots, "bytes_per_step": n, "steps": steps},
                             tag=f"noisy-r{robots:02d}-b{n:06d}",
                             forward_stdio=False))
    return out


def bench_multi_instance(instance_counts: list[int], steps: int) -> list[PerfRecord]:
    """Launch K parallel omnisim-bin processes against the same fixed world.

    Per-instance perf logs go to distinct files. We also check whether
    the shared `omnisim_log.txt` was clobbered (a pre-fix-1 indicator)."""
    out = []
    world = gen_multi_instance_world(steps=steps)
    shared_log = REPO_ROOT / "omnisim_log.txt"
    for k in instance_counts:
        # Try to clear the shared log. On Windows, a previous omnisim-bin process
        # may still hold the handle briefly after exit; that itself is informative
        # (and exactly the multi-instance contention we want to fix), so don't
        # treat it as a hard failure.
        shared_log_clear_failed = False
        if shared_log.exists():
            try:
                shared_log.unlink()
            except OSError as e:
                shared_log_clear_failed = True
                print(f"[bench]   note: could not clear {shared_log.name}: {e}")
        # Each child gets its own OMNISIM_LOG_PATH so the per-instance-log fix
        # can be verified by checking the file exists after the run.
        per_child_logs: list[Path] = []
        records = []
        with ThreadPoolExecutor(max_workers=k) as pool:
            futures = []
            for i in range(k):
                tag = f"multi-instance-k{k}-i{i}"
                child_log = LOG_DIR / f"{tag}.omnisim.log"
                if child_log.exists():
                    try:
                        child_log.unlink()
                    except OSError:
                        pass
                per_child_logs.append(child_log)
                # Let the simulator pick its own port (it scans up from default)
                # so two instances don't collide.
                futures.append(pool.submit(run_world, world, "multi-instance-child",
                                           {"k": k, "instance": i, "steps": steps},
                                           tag, None, 900, child_log))
            for fut in as_completed(futures):
                records.append(fut.result())
        # Aggregate child wall times: max is the parallel wall, sum is total CPU.
        wall_max = max(r.wall_time_s for r in records)
        wall_sum = sum(r.wall_time_s for r in records)
        # Average physics-step time across instances (for headroom check).
        phys_avg = sum(r.avg.get("physics(ms)", 0.0) for r in records) / max(len(records), 1)
        # Did the shared log get touched? (presence ≠ proof of clobber, but tells
        # us at least one instance still writes there.)
        shared_present = shared_log.exists()
        agg = PerfRecord(
            scenario="multi-instance",
            params={"k": k, "steps": steps},
            log_path="(see children)",
            wall_time_s=wall_max,
            returncode=max(r.returncode for r in records),
        )
        agg.avg = {
            "physics(ms)": round(phys_avg, 3),
            "wall_max_s": round(wall_max, 3),
            "wall_sum_s": round(wall_sum, 3),
            "scaling_efficiency": round(records[0].wall_time_s / wall_max, 3) if k > 1 else 1.0,
        }
        agg.notes.append(f"shared omnisim_log.txt present after run: {shared_present}")
        if shared_log_clear_failed:
            agg.notes.append("shared omnisim_log.txt was locked at start of run "
                             "(multi-instance file contention)")
        # Per-instance-log fix verification: each child should have produced its
        # own log file because we set OMNISIM_LOG_PATH per child.
        per_child_present = sum(1 for p in per_child_logs if p.exists() and p.stat().st_size > 0)
        agg.avg["per_instance_logs_present"] = per_child_present
        agg.avg["per_instance_logs_expected"] = len(per_child_logs)
        if per_child_present < len(per_child_logs):
            missing = [p.name for p in per_child_logs if not (p.exists() and p.stat().st_size > 0)]
            agg.notes.append(f"per-instance log MISSING for: {missing}")
        else:
            agg.notes.append(f"per-instance logs present: {per_child_present}/{len(per_child_logs)}")
        for r in records:
            agg.notes.append(f"child i={r.params['instance']} wall={r.wall_time_s}s rc={r.returncode}")
        out.append(agg)
        out.extend(records)
    return out


# --- reload-creep --------------------------------------------------------

def bench_reload_creep(world_path: Path, iterations: int, port: int = 6798) -> list[PerfRecord]:
    """Launch the harness, hit /world/load N times on the same world, measure
    process-tree RSS after each load. Indicates which caches grow across world
    reloads (target of plan item #2).
    """
    try:
        import psutil  # noqa: F401
    except ImportError:
        rec = PerfRecord(scenario="reload-creep", params={"world": world_path.name},
                         log_path="", wall_time_s=0.0, returncode=2)
        rec.notes.append("psutil not installed; skip reload-creep bench")
        return [rec]

    import urllib.request
    import urllib.error
    import psutil

    env = os.environ.copy()
    env["OMNISIM_HOME"] = str(REPO_ROOT)
    binary = find_binary()
    if sys.platform == "win32":
        env["PATH"] = str(binary.parent) + os.pathsep + env.get("PATH", "")

    harness_cmd = [
        sys.executable,
        str(REPO_ROOT / "scripts" / "harness" / "omnisim_harness.py"),
        "--port", str(port),
    ]
    print(f"[bench] reload-creep: starting harness on port {port}")
    harness = subprocess.Popen(harness_cmd, env=env, cwd=REPO_ROOT,
                               stdout=subprocess.PIPE, stderr=subprocess.PIPE)

    def harness_rss() -> int:
        # Sum RSS across the harness process tree (harness + its omnisim-bin child).
        total = 0
        try:
            p = psutil.Process(harness.pid)
            total += p.memory_info().rss
            for c in p.children(recursive=True):
                try:
                    total += c.memory_info().rss
                except (psutil.NoSuchProcess, psutil.AccessDenied):
                    pass
        except psutil.NoSuchProcess:
            pass
        return total

    def http_get(path: str, timeout: float = 10.0) -> bytes:
        with urllib.request.urlopen(f"http://127.0.0.1:{port}{path}", timeout=timeout) as r:
            return r.read()

    def http_post(path: str, body: dict, timeout: float = 60.0) -> bytes:
        data = json.dumps(body).encode()
        req = urllib.request.Request(f"http://127.0.0.1:{port}{path}",
                                     data=data, headers={"Content-Type": "application/json"})
        with urllib.request.urlopen(req, timeout=timeout) as r:
            return r.read()

    creep: list[dict] = []
    rec = PerfRecord(
        scenario="reload-creep",
        params={"world": world_path.name, "iterations": iterations},
        log_path="(harness, no perf log)",
        wall_time_s=0.0,
        returncode=0,
    )

    try:
        # Wait for the harness to be live.
        deadline = time.time() + 30
        while time.time() < deadline:
            try:
                http_get("/healthz", timeout=1.0)
                break
            except (urllib.error.URLError, ConnectionError):
                time.sleep(0.2)
        else:
            rec.returncode = 1
            rec.notes.append("harness did not become healthy within 30s")
            return [rec]

        t0 = time.time()
        for i in range(iterations):
            iter_start = time.time()
            hot = None
            ok = False
            try:
                resp = http_post("/world/load",
                                 {"path": str(world_path.relative_to(REPO_ROOT)).replace("\\", "/")},
                                 timeout=120)
                resp_json = json.loads(resp.decode("utf-8", errors="replace"))
                ok = resp_json.get("ok", False)
                hot = resp_json.get("hot_reloaded")
            except Exception as e:
                rec.notes.append(f"iter {i}: load failed: {e}")
            time.sleep(1.5)  # let process settle so RSS reflects post-load steady state
            rss = harness_rss()
            wall = round(time.time() - iter_start, 3)
            creep.append({"iter": i, "rss_bytes": rss, "rss_mb": round(rss / 1024 / 1024, 2),
                          "wall_s": wall, "ok": ok, "hot_reloaded": hot})
            tag = "hot" if hot else "cold"
            print(f"[bench]   iter {i:>2}  rss={rss/1024/1024:>7.1f} MB  wall={wall}s  ok={ok}  reload={tag}")
        rec.wall_time_s = round(time.time() - t0, 3)
    finally:
        try:
            harness.terminate()
            harness.wait(timeout=10)
        except subprocess.TimeoutExpired:
            harness.kill()
            harness.wait(timeout=5)

    rec.avg["iterations"] = len(creep)
    hot_iters = [c for c in creep if c.get("hot_reloaded")]
    rec.avg["hot_reload_iterations"] = len(hot_iters)
    if creep:
        rec.avg["rss_mb_first"] = creep[0]["rss_mb"]
        rec.avg["rss_mb_last"] = creep[-1]["rss_mb"]
        rec.avg["rss_mb_growth"] = round(creep[-1]["rss_mb"] - creep[0]["rss_mb"], 2)
        rec.avg["wall_s_first"] = creep[0]["wall_s"]
        rec.avg["wall_s_last"] = creep[-1]["wall_s"]
    if len(hot_iters) >= 2:
        rec.avg["rss_mb_hot_first"] = hot_iters[0]["rss_mb"]
        rec.avg["rss_mb_hot_last"] = hot_iters[-1]["rss_mb"]
        rec.avg["rss_mb_hot_growth"] = round(hot_iters[-1]["rss_mb"] - hot_iters[0]["rss_mb"], 2)
        rec.avg["rss_mb_per_hot_iter"] = round(
            (hot_iters[-1]["rss_mb"] - hot_iters[0]["rss_mb"]) / max(len(hot_iters) - 1, 1), 3)
    rec.notes.append(json.dumps(creep))
    return [rec]


def cmd_reload_creep(args):
    world = Path(args.world).resolve()
    if not world.exists():
        raise SystemExit(f"world not found: {world}")
    return bench_reload_creep(world, iterations=args.iterations, port=args.port)


# --- cleanup -------------------------------------------------------------

# Command-line substrings used to identify bench-spawned controllers. We only
# kill Python processes whose command line matches one of these — never bare
# `python.exe`.
_BENCH_CONTROLLER_PATTERNS = (
    "bench_quit",
    "bench_noisy",
    "bench_camera",
    "omnibot_random",
    "omnibot_controller",
)


def cmd_cleanup(args) -> list[PerfRecord]:
    """Kill orphan omnisim-bin processes and bench controller children left
    behind by failed/interrupted runs. These hold lib/controller/Controller.dll
    open on Windows, which blocks the next `controller-libs` link, and hold
    msys64/mingw64/bin/omnisim-bin.exe open which blocks the next core link.
    """
    try:
        import psutil
    except ImportError:
        print("[bench] cleanup: psutil not installed — install with `pip install psutil`")
        return []

    killed_webots: list[int] = []
    killed_controllers: list[tuple[int, str]] = []

    for proc in psutil.process_iter(attrs=["pid", "name", "cmdline"]):
        try:
            name = (proc.info["name"] or "").lower()
            cmdline = " ".join(proc.info["cmdline"] or [])

            if name in ("omnisim-bin.exe", "omnisim-bin", "webots.exe", "webots"):
                killed_webots.append(proc.info["pid"])
                if not args.dry_run:
                    proc.kill()
                continue

            if name.startswith("python") and any(p in cmdline for p in _BENCH_CONTROLLER_PATTERNS):
                # Truncate cmdline for readable output.
                short = cmdline if len(cmdline) <= 100 else cmdline[:97] + "..."
                killed_controllers.append((proc.info["pid"], short))
                if not args.dry_run:
                    proc.kill()
        except (psutil.NoSuchProcess, psutil.AccessDenied):
            continue

    verb = "would kill" if args.dry_run else "killed"
    if killed_webots:
        print(f"[bench] cleanup: {verb} {len(killed_webots)} omnisim-bin process(es): {killed_webots}")
    if killed_controllers:
        print(f"[bench] cleanup: {verb} {len(killed_controllers)} bench controller process(es):")
        for pid, cmd in killed_controllers:
            print(f"          pid={pid}  {cmd}")
    if not killed_webots and not killed_controllers:
        print("[bench] cleanup: nothing to kill")
    return []


# --- compare -------------------------------------------------------------

def fmt_delta(before: float, after: float) -> str:
    if before == 0:
        return f"{after:.2f} (no baseline)"
    pct = (after - before) / before * 100
    arrow = "v" if pct < 0 else "^"
    return f"{before:.2f} -> {after:.2f} ({arrow}{abs(pct):.1f}%)"


def _is_spread_field(metric: str) -> bool:
    return metric.endswith(("_min", "_max", "_stdev"))


def _spread_for(avg: dict, metric: str) -> Optional[float]:
    """Return the larger-side spread (max - median or median - min) for the
    metric, or None if no spread fields are present."""
    median = avg.get(metric)
    mn = avg.get(f"{metric}_min")
    mx = avg.get(f"{metric}_max")
    if not isinstance(median, (int, float)):
        return None
    if isinstance(mn, (int, float)) and isinstance(mx, (int, float)):
        return max(median - mn, mx - median)
    return None


def compare(baseline_path: Path, after_path: Path) -> None:
    before = json.loads(baseline_path.read_text())
    after = json.loads(after_path.read_text())

    def index(records):
        # When --repeats > 1, the file contains both aggregated records (with
        # _min/_max/_stdev fields) and the raw individual runs. Both share the
        # same (scenario, params) key. Prefer the aggregate.
        by_key: dict = {}
        for r in records:
            k = (r["scenario"], json.dumps(r["params"], sort_keys=True))
            existing = by_key.get(k)
            if existing is None:
                by_key[k] = r
                continue
            existing_has_spread = any(m.endswith("_stdev") for m in existing.get("avg", {}))
            new_has_spread = any(m.endswith("_stdev") for m in r.get("avg", {}))
            if new_has_spread and not existing_has_spread:
                by_key[k] = r
        return by_key

    bi = index(before["records"])
    ai = index(after["records"])

    print(f"\n=== {baseline_path.name} vs {after_path.name} ===\n")
    keys = sorted(set(bi) | set(ai))
    for k in keys:
        scenario, params = k
        b = bi.get(k)
        a = ai.get(k)
        if not b or not a:
            print(f"  [skip] {scenario} {params} (missing in one side)")
            continue
        print(f"\n* {scenario} {params}")
        b_avg = b.get("avg", {})
        a_avg = a.get("avg", {})
        # Skip the *_min/*_max/*_stdev sibling fields in the listing — we
        # surface their info inline as "(noise: +/- X)" annotations instead.
        all_metrics = set(b_avg) | set(a_avg)
        all_metrics = {m for m in all_metrics if not _is_spread_field(m)}
        for metric in sorted(all_metrics):
            if metric.startswith("_"):
                continue
            bv = b_avg.get(metric, 0.0)
            av = a_avg.get(metric, 0.0)
            if not (isinstance(bv, (int, float)) and isinstance(av, (int, float))):
                continue
            line = f"    {metric:32s} {fmt_delta(bv, av)}"
            # Append noise-floor context if available.
            spreads = []
            for tag, val in (("base", _spread_for(b_avg, metric)),
                             ("aft", _spread_for(a_avg, metric))):
                if val is not None:
                    spreads.append(f"{tag}+/-{val:.3f}")
            if spreads:
                noise = max(_spread_for(b_avg, metric) or 0,
                            _spread_for(a_avg, metric) or 0)
                delta_abs = abs(av - bv)
                marker = " (within noise)" if delta_abs <= noise else ""
                line += f"   [{', '.join(spreads)}{marker}]"
            print(line)


