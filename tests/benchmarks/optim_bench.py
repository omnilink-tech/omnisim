# --- binary discovery ----------------------------------------------------

def find_binary() -> Path:
    override = os.environ.get("OMNISIM_BENCH_BINARY")
    if override:
        binary = Path(override).expanduser().resolve()
        if binary.is_file():
            return binary
        raise SystemExit(f"OMNISIM_BENCH_BINARY does not exist: {binary}")

    # Always prefer the repo-local binary — bench is repo-local.
    # Ignore any system OMNISIM_HOME set in the user's env.
    home = REPO_ROOT
    if sys.platform == "win32":
        candidates = [
            home / "msys64" / "mingw64" / "bin" / "omnisim-bin.exe",
            home / "msys64" / "mingw64" / "bin" / "webots.exe",
        ]
    elif sys.platform == "darwin":
        candidates = [home / "Contents" / "MacOS" / "omnisim", home / "Contents" / "MacOS" / "webots"]
    else:
        candidates = [home / "bin" / "omnisim-bin", home / "webots"]
    for c in candidates:
        if c.exists():
            return c
    raise SystemExit(f"omnisim-bin binary not found under {home}")


