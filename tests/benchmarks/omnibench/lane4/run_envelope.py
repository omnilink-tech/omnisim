def run_window(binpath, world, n_log, tag, tmp, timeout_s, solver):
    csv = tmp / ("perf_%s.csv" % tag)
    elog = tmp / ("engine_%s.log" % tag)
    nlog = tmp / ("newton_%s.log" % tag)
    console = tmp / ("console_%s.log" % tag)
    for p in (csv, elog, nlog, console, Path(str(elog) + ".newton.json")):
        if p.exists():
            p.unlink()
    env = engine_launch.build_env("newton", elog, repo=REPO, extra={
        # per-run newton log: the default is a single shared
        # .build_tmp/newton_solver.log that every run APPENDS to, so a sweep
        # would read the previous N's overflow as its own.
        "OMNISIM_NEWTON_LOG": str(nlog),
        # verbose peak trace; without it only the latched overflow warning is
        # emitted and the sweep gets a boolean where it needs nefc/njmax.
        "OMNISIM_NEWTON_CONSTRAINT_STATS": "10",
    })
    rc, wall, timed_out = engine_launch.launch_once(
        binpath, world, env, console, timeout_s,
        extra_args=("--stdout", "--stderr",
                    "--log-performance=%s,%d" % (csv, n_log)))
    verdict = engine_launch.newton_verdict(elog)
    engine, reason = engine_launch.engine_attribution(verdict)
    return {"rc": rc, "wall_s": wall, "timed_out": timed_out,
            "row": parse_perf_csv(csv), "engine": engine, "reason": reason,
            "telemetry": read_constraint_telemetry(nlog, elog),
            "engine_log": str(elog),
            "solver_reported": verdict.get("solver")}


def measure_cell(binpath, scene, n, solver, tmp, timeout_s, repeats,
                 caps_lines=""):
    steps = N_LONG + STEP_MARGIN
    world = gen_world(WORLDS_DIR / ("env_%s_n%d_%s.wbt" % (scene, n, solver)),
                      scene, n, steps, solver, caps_lines)
    samples, telemetry, engine, reason, last_log = [], {}, None, None, None
    for rep in range(repeats):
        pair, ok = {}, True
        for label, n_log in (("short", N_SHORT), ("long", N_LONG)):
            tag = "%s_n%d_%s_%s_r%d" % (scene, n, solver, label, rep)
            res = run_window(binpath, world, n_log, tag, tmp, timeout_s, solver)
            engine, reason, last_log = res["engine"], res["reason"], res["engine_log"]
            t = res["telemetry"]
            # keep the WORST telemetry seen across windows/reps: an overflow
            # in any window is an overflow for this N
            if t["sampled"]:
                telemetry = _merge_telemetry(telemetry, t)
            row = res["row"]
            if row is None or row["steps"] != n_log or engine != "omnisim-newton":
                log("    [drop] n=%d %s rep%d: rc=%s engine=%s steps=%s%s"
                    % (n, label, rep, res["rc"], engine,
                       row["steps"] if row else None,
                       " TIMEOUT" if res["timed_out"] else ""))
                ok = False
                break
            pair[label] = row
        if not ok:
            continue
        s, l = pair["short"], pair["long"]
        dn = l["steps"] - s["steps"]
        cell = {}
        for phase in ("physics", "postPhysics", "prePhysics"):
            cell[phase] = (l[phase] - s[phase]) / dn
        cell["total"] = sum(cell[p] for p in
                            ("physics", "postPhysics", "prePhysics"))
        # A NEGATIVE per-step cost is physically impossible and means the two
        # windows did not differ only in their logging window -- on the GPU
        # path with N controller processes, startup variance can exceed the
        # difference the method relies on. Measured: n=12 rovers produced
        # -13.5171 ms/step, which the summary would have turned into a
        # "4000000000x realtime" envelope. Drop the sample; the cell degrades
        # to a GAP that still carries its constraint telemetry, which is the
        # part of the rover sweep that matters.
        if cell["total"] <= 0.0:
            log("    [drop] n=%d rep%d: differencing gave a NEGATIVE per-step "
                "cost (%.4f ms) -- the two windows did not do identical work"
                % (n, rep, cell["total"]))
            continue
        samples.append(cell)
    if not samples:
        return None, telemetry, engine, reason, last_log
    med = {k: statistics.median(s[k] for s in samples) for k in samples[0]}
    med["n_samples"] = len(samples)
    if len(samples) > 1:
        med["total_spread_pct"] = 100.0 * (
            max(s["total"] for s in samples) - min(s["total"] for s in samples)
        ) / max(1e-12, med["total"])
    return med, telemetry, engine, reason, last_log


def _merge_telemetry(a, b):
    if not a:
        return dict(b)
    out = dict(a)
    for k in ("peak_nefc", "peak_ncon"):
        if b.get(k) is not None:
            out[k] = max(out.get(k) or 0, b[k])
    for k in ("njmax", "nconmax"):
        if b.get(k) is not None:
            out[k] = b[k]
    out["overflow"] = bool(out.get("overflow")) or bool(b.get("overflow"))
    out["sampled"] = bool(out.get("sampled")) or bool(b.get("sampled"))
    if b.get("first_overflow_tick") is not None:
        prev = out.get("first_overflow_tick")
        out["first_overflow_tick"] = (b["first_overflow_tick"] if prev is None
                                      else min(prev, b["first_overflow_tick"]))
    return out


