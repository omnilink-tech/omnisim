"""OmniBench lane 4b — the RESOURCE ENVELOPE.

    python tests/benchmarks/omnibench/lane4/run_envelope.py
    python .../run_envelope.py --sweep rovers --solver mujoco_warp
    python .../run_envelope.py --sweep boxes --sizes 1 20 200 --repeats 3

Two questions no other lane answers, both per-machine:

**How big a scene does THIS box carry in real time?**
Lane 2 measures batched throughput for one robot at three batch sizes;
step_cost measures what one tick costs at a given N. Neither states an
*envelope* — the N at which a single world stops keeping up with wall clock —
which is the number that decides whether a scenario is buildable at all.
This lane brackets it: the largest measured N still at or above 1x realtime
and the smallest measured N below it. It is a BRACKET, never an
interpolation: the cost curve has a fixed conversion overhead and a
contact-dependent term, and fitting through a cliff is how you publish a
number nobody can reproduce.

**Where does the scene start degrading SILENTLY?**
This is the part that makes the lane worth building. On the GPU
(`mujoco_warp`) path, mujoco_warp allocates a fixed constraint buffer and
DROPS every constraint row past `njmax` without raising anything a normal run
can see — its own diagnostic is a `wp.printf` inside a warp kernel, discarded
outright by a GUI-subsystem `omnisim-bin.exe`. So the symptom is "the physics
feels wrong at scale", with a clean log and exit code 0. AGENTS.md documents
the threshold in prose (~9 four-wheeled robots against the 256 default);
until this lane it was pinned by nothing, so nobody would notice it moving.

The rover sweep drives every wheel for the whole window — a parked robot is a
different, easier contact problem, and the credibility checklist this suite
follows forbids idle actions in a throughput number.

Scope, stated rather than implied:
  * The cap exists ONLY on the GPU path. CPU `mj_step` grows its efc arrays
    dynamically, so there is no truncation to detect and the cliff sweep on
    `--solver mujoco` correctly finds nothing. That is a real difference
    between the two solvers, not a gap in the instrument.
  * Wall-clock rows step a whole engine process (controller IPC included).
    They are not comparable to a bare-library step time (SPEC.md honesty
    rule 5).
"""
