def _grid(n, pitch):
    """Lay N items on a square grid, centred, spaced so none of them touch."""
    side = int(n ** 0.5) + 1
    for i in range(n):
        r, c = divmod(i, side)
        yield i, (c - (side - 1) / 2.0) * pitch, (r - (side - 1) / 2.0) * pitch


def gen_world(path, scene, n, steps, solver, caps_lines=""):
    pitch = 0.5 if scene == "boxes" else 1.2
    span = max(20.0, (int(n ** 0.5) + 2) * pitch * 2)
    text = HEADER % {"scene": scene, "n": n, "solver": solver, "dt": _fmt(DT_MS),
                     "floor": _fmt(span), "steps": steps, "caps": caps_lines}
    if scene == "boxes":
        for i, x, y in _grid(n, pitch):
            text += BOX % {"i": i, "x": _fmt(x), "y": _fmt(y)}
    else:
        for i, x, y in _grid(n, pitch):
            wheels = ""
            for name, wx, wy in (("w_fl", 0.15, 0.18), ("w_fr", 0.15, -0.18),
                                 ("w_rl", -0.15, 0.18), ("w_rr", -0.15, -0.18)):
                wheels += WHEEL % {"name": name, "wx": _fmt(wx), "wy": _fmt(wy)}
            text += ROVER % {"i": i, "x": _fmt(x), "y": _fmt(y), "wheels": wheels}
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    return path


