def sweep(binpath, scene, sizes, solver, tmp, timeout_s, repeats, out,
          caps_lines=""):
    rows, realtime_ok, realtime_fail, first_overflow = [], [], [], None
    for n in sizes:
        log("  %s n=%d (%s) ..." % (scene, n, solver))
        cell, telem, engine, reason, elog = measure_cell(
            binpath, scene, n, solver, tmp, timeout_s, repeats, caps_lines)
        machine = results_mod.machine_fingerprint(engine_log_path=elog)
        devs = [reason] if reason else []
        devs.append("wall-clock steps a whole engine process (controller IPC "
                    "included); not comparable to a bare-library step time")
        if cell is None:
            log("    -> no measurement (all reps dropped)")
            rows.append(results_mod.append_row(out, results_mod.make_row(
                test="envelope_%s" % scene, engine=engine or "omnisim-unverified",
                dt_ms=DT_MS,
                metrics={"n": n, "solver": solver, "measured": False,
                         "constraint_telemetry": telem},
                wall_ms_per_step=0.0, steps=0, sim_seconds=0.0,
                deviations=devs + ["no window pair survived; cell is a GAP, "
                                   "not a zero"],
                machine=machine)))
            continue
        rtf = DT_MS / max(1e-9, cell["total"])
        (realtime_ok if rtf >= 1.0 else realtime_fail).append(n)
        if telem.get("overflow") and first_overflow is None:
            first_overflow = n
        log("    total %.4f ms/step  realtime %.2fx  nefc %s/%s%s"
            % (cell["total"], rtf, telem.get("peak_nefc"), telem.get("njmax"),
               "  *** CONSTRAINT OVERFLOW ***" if telem.get("overflow") else ""))
        rows.append(results_mod.append_row(out, results_mod.make_row(
            test="envelope_%s" % scene, engine=engine, dt_ms=DT_MS,
            metrics={
                "n": n, "solver": solver, "measured": True,
                "ms_per_step_total": cell["total"],
                "ms_per_step_physics": cell["physics"],
                "ms_per_step_post": cell["postPhysics"],
                "realtime_factor": rtf,
                "keeps_realtime": rtf >= 1.0,
                "reps": cell.get("n_samples"),
                "spread_pct": cell.get("total_spread_pct"),
                "constraint_telemetry": telem,
            },
            wall_ms_per_step=cell["total"],
            steps=N_LONG - N_SHORT,
            sim_seconds=(N_LONG - N_SHORT) * DT_MS / 1000.0,
            deviations=devs, machine=machine)))
    return rows, realtime_ok, realtime_fail, first_overflow


def summary(out, scene, sizes, solver, realtime_ok, realtime_fail,
            first_overflow, telem_sampled, n_cells=0):
    largest_ok = max(realtime_ok) if realtime_ok else None
    smallest_fail = min(realtime_fail) if realtime_fail else None
    measured = len(realtime_ok) + len(realtime_fail)
    devs = []
    if n_cells and measured * 2 < n_cells:
        # Not a footnote: if most cells produced no timing, the "envelope" is
        # a statement about the two or three sizes that survived. Measured on
        # mujoco_warp, where per-run startup variance across N controller
        # processes routinely exceeds the difference the two-window method
        # relies on, yielding negative (rejected) per-step costs.
        devs.append(
            "ONLY %d of %d sizes produced a timing measurement. The two-window "
            "differencing method assumes both runs do identical work and "
            "differ only in the logging window; on this path the run-to-run "
            "startup variance exceeds that difference and the subtraction goes "
            "negative, so those cells are GAPS. Read the envelope as covering "
            "the surviving sizes only, and prefer the CPU (`mujoco`) sweep for "
            "any realtime claim." % (measured, n_cells))
    devs.append(
        "the realtime envelope is a BRACKET between two measured sizes, never "
        "an interpolation: the cost curve has a fixed conversion term and a "
        "contact-dependent term, and fitting through that is how an "
        "unreproducible headline gets published")
    if not telem_sampled:
        devs.append(
            "constraint telemetry never sampled on this sweep: mujoco_warp "
            "allocates the fixed njmax buffer, CPU mj_step grows its efc "
            "arrays dynamically. 'No overflow' here means THERE IS NO CAP on "
            "this solver path, not that a cap was tested and cleared.")
    elif first_overflow is None:
        # The translation-audit rule, applied here: a green that cannot be
        # made to go red is not evidence. Measured 2026-08-10 on machine
        # 9722d23d12a3, driven 4-wheeled rovers under mujoco_warp: peak nefc
        # tracked 32*N exactly (32/128/256/384/512 at N=1/4/8/12/16) and the
        # ALLOCATED cap tracked it too, so nothing ever overflowed -- and
        # three attempts to force one all read 384/384 at N=12: default,
        # WorldInfo.newtonNjmax 256, and OMNISIM_NEWTON_NJMAX=64.
        devs.append(
            "NO OVERFLOW WAS OBSERVED **AND THE DETECTOR COULD NOT BE MADE TO "
            "FIRE**, so this row is NOT a clean bill of health. On this "
            "runtime the allocated constraint buffer tracked the model "
            "(cap == peak nefc == 32*N), and neither WorldInfo.newtonNjmax "
            "nor OMNISIM_NEWTON_NJMAX changed the allocated cap in a "
            "controlled retry. Either the runtime now auto-sizes the buffer "
            "and the njmax knob is inert, or Data.njmax is not the cap that "
            "governs truncation. Re-run with --pin-njmax well below 32*N; if "
            "it still will not go red, treat every 'no overflow' verdict on "
            "this path as UNVALIDATED. Scope: this scene is generated 4-wheel "
            "rovers, NOT the 10-Husky world AGENTS.md's ~9-robot threshold "
            "was measured on -- do not read this as refuting that number.")
    return results_mod.append_row(out, results_mod.make_row(
        test="envelope_summary_%s" % scene, engine="omnisim-newton", dt_ms=DT_MS,
        metrics={
            "scene": scene, "solver": solver, "sizes_measured": list(sizes),
            "largest_n_at_realtime": largest_ok,
            "smallest_n_below_realtime": smallest_fail,
            # All four cases stated explicitly. An unguarded "between %s and
            # %s" printed "between None and 12" on a sweep whose only measured
            # cell was already below realtime, and "between 16 and 4" on one
            # whose large cells produced negative (rejected) timings -- both
            # read as findings rather than as the gaps they were.
            "realtime_envelope": (
                "no cell produced a measurement" if not (realtime_ok or realtime_fail)
                else "N >= %s still at realtime; ceiling not reached by this "
                     "sweep" % max(realtime_ok) if not realtime_fail
                else "below realtime already at the smallest measured N=%s"
                     % smallest_fail if largest_ok is None
                else "between %s and %s" % (largest_ok, smallest_fail)),
            "first_n_with_constraint_overflow": first_overflow,
            "constraint_telemetry_sampled": telem_sampled,
            # False means "we never saw the detector fire", which is NOT the
            # same as "there was nothing to detect". Consumers must branch on
            # this before quoting the overflow result either way.
            "cliff_detector_validated": first_overflow is not None,
        },
        wall_ms_per_step=0.0, steps=0, sim_seconds=0.0,
        deviations=devs, machine=results_mod.machine_fingerprint()))


def recompute_summary(out):
    """Rebuild the summary rows in `out` from its own cell rows.

    Only the interpretation is recomputed; every measurement is preserved
    byte-for-byte. Cell rows are keyed by (scene, solver) exactly as the sweep
    grouped them, and a cell that carries `measured: false` stays a gap.
    """
    if not out.exists():
        log("no such results file: %s" % out)
        return 2
    rows = results_mod.read_rows(out)
    cells = [r for r in rows if r["test"].startswith("envelope_")
             and not r["test"].startswith("envelope_summary_")]
    if not cells:
        log("no cell rows in %s" % out)
        return 2
    groups = {}
    for r in cells:
        m = r["metrics"]
        groups.setdefault((m.get("solver"), r["test"].split("envelope_", 1)[1]),
                          []).append(r)
    out.write_text("".join(json.dumps(r) + "\n" for r in cells),
                   encoding="utf-8", newline="\n")
    for (solver, scene), rs in sorted(groups.items(), key=lambda kv: str(kv[0])):
        ok, fail, first_overflow, sampled = [], [], None, False
        sizes = []
        for r in sorted(rs, key=lambda r: r["metrics"]["n"]):
            m = r["metrics"]
            n = int(m["n"])
            sizes.append(n)
            t = m.get("constraint_telemetry") or {}
            sampled = sampled or bool(t.get("sampled"))
            if t.get("overflow") and first_overflow is None:
                first_overflow = n
            if not m.get("measured"):
                continue
            (ok if m.get("keeps_realtime") else fail).append(n)
        s = summary(out, scene, sizes, solver, ok, fail, first_overflow,
                    sampled, n_cells=len(sizes))
        log("  %s/%s -> %s" % (scene, solver,
                               s["metrics"]["realtime_envelope"]))
    log("recomputed %d summaries from %d cells -> %s"
        % (len(groups), len(cells), out))
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--sweep", choices=("boxes", "rovers", "both"),
                    default="both")
    ap.add_argument("--sizes", type=int, nargs="*", default=None)
    ap.add_argument("--solver", default=None,
                    help="mujoco (CPU, default for boxes) or mujoco_warp "
                         "(GPU -- the only path with a constraint cap)")
    ap.add_argument("--repeats", type=int, default=2)
    ap.add_argument("--timeout", type=float, default=300.0)
    ap.add_argument("--pin-njmax", type=int, default=None,
                    help="declare WorldInfo.newtonNjmax/newtonNconmax at this "
                         "value. THE SELF-TEST FOR THE CLIFF DETECTOR: a green "
                         "'no overflow' is not evidence unless the same "
                         "instrument can be made to go red. Pin it below "
                         "32*N and the overflow must fire.")
    ap.add_argument("--work-dir", type=Path, default=None)
    ap.add_argument("--keep-worlds", action="store_true")
    ap.add_argument("--recompute-summary", action="store_true",
                    help="re-derive the summary rows in --out from the CELL "
                         "rows already in it, without touching the engine. "
                         "Cells are measurements; summaries are just their "
                         "interpretation, so a change to how the envelope is "
                         "stated must not cost a re-measurement (and must not "
                         "tempt anyone into re-running until the wording "
                         "comes out nicer).")
    a = ap.parse_args(argv)

    if a.recompute_summary:
        return recompute_summary(Path(a.out))

    binpath = engine_launch.resolve_binary(REPO)
    if binpath is None or not Path(binpath).exists():
        log("omnisim-bin not found -- build first (AGENTS.md section 2)")
        return 2
    tmp = a.work_dir or (HERE / "results" / "_envelope_work")
    tmp.mkdir(parents=True, exist_ok=True)
    out = Path(a.out)
    if out.exists():
        out.unlink()
    out.parent.mkdir(parents=True, exist_ok=True)

    scenes = ["boxes", "rovers"] if a.sweep == "both" else [a.sweep]
    t0 = time.perf_counter()
    for scene in scenes:
        sizes = a.sizes or (BOX_SIZES if scene == "boxes" else ROVER_SIZES)
        # Rovers default to the GPU path on purpose: that is the only solver
        # with a fixed constraint buffer, so it is the only place the silent
        # cliff this lane exists to find can occur.
        solver = a.solver or ("mujoco" if scene == "boxes" else "mujoco_warp")
        caps_lines = ""
        if a.pin_njmax is not None:
            caps_lines = ("  newtonNjmax %d\n  newtonNconmax %d\n"
                          % (a.pin_njmax, a.pin_njmax))
            log("lane4b: njmax/nconmax PINNED at %d (detector self-test)"
                % a.pin_njmax)
        log("lane4b envelope: scene=%s solver=%s sizes=%s"
            % (scene, solver, list(sizes)))
        rows, ok, fail, overflow = sweep(binpath, scene, sizes, solver, tmp,
                                         a.timeout, a.repeats, out, caps_lines)
        sampled = any((r["metrics"].get("constraint_telemetry") or {})
                      .get("sampled") for r in rows)
        s = summary(out, scene, sizes, solver, ok, fail, overflow, sampled,
                    n_cells=len(list(sizes)))
        m = s["metrics"]
        log("  -> realtime envelope: %s" % m["realtime_envelope"])
        log("  -> first N with a SILENT constraint overflow: %s"
            % m["first_n_with_constraint_overflow"])
    log("lane4b done in %.1f s -> %s" % (time.perf_counter() - t0, out))
    if not a.keep_worlds:
        for w in WORLDS_DIR.glob("env_*.wbt"):
            try:
                w.unlink()
            except OSError:
                pass
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
