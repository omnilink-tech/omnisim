PEAK_RE = re.compile(
    r"constraint peak:\s*nefc=(\d+)/(\S+)\s+ncon=(\d+)/(\S+)\s+tick=(\d+)(.*)")


def read_constraint_telemetry(newton_log, engine_log):
    """-> {peak_nefc, njmax, peak_ncon, nconmax, overflow, first_overflow_tick}

    Two independent channels, both read, because each can be missing for a
    reason that is not "no overflow": the engine log carries the LATCHED
    one-shot warning (present even when verbose tracing is off), and
    newton_solver.log carries the per-peak trace with the actual numbers. A
    verdict of "no overflow" is only trustworthy when the telemetry was
    actually running, so `sampled` is reported alongside it.
    """
    out = {"peak_nefc": None, "njmax": None, "peak_ncon": None,
           "nconmax": None, "overflow": False, "first_overflow_tick": None,
           "sampled": False}
    try:
        for line in Path(newton_log).read_text(encoding="utf-8",
                                               errors="replace").splitlines():
            m = PEAK_RE.search(line)
            if not m:
                continue
            out["sampled"] = True
            nefc, njmax, ncon, nconmax, tick, tail = m.groups()
            out["peak_nefc"] = max(out["peak_nefc"] or 0, int(nefc))
            out["peak_ncon"] = max(out["peak_ncon"] or 0, int(ncon))
            out["njmax"] = njmax
            out["nconmax"] = nconmax
            if "OVERFLOW" in tail:
                out["overflow"] = True
                if out["first_overflow_tick"] is None:
                    out["first_overflow_tick"] = int(tick)
    except OSError:
        pass
    try:
        eng = Path(engine_log).read_text(encoding="utf-8", errors="replace")
        if "CONSTRAINT BUFFER OVERFLOW" in eng:
            out["overflow"] = True
            out["sampled"] = True
    except OSError:
        pass
    return out


