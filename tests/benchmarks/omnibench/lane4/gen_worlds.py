"""gen_worlds.py — emit one .wbt per lane-4 capability probe.

Deterministic: same registry -> byte-identical worlds. The worlds are
COMMITTED rather than generated into a temp dir, for one reason: a capability
claim that a third party cannot load and re-run is a self-attestation again,
which is the exact weakness lane 4 exists to remove. Every verdict this lane
publishes has a file behind it that anybody can open.

    python tests/benchmarks/omnibench/lane4/gen_worlds.py [--check]

`--check` regenerates into memory and diffs against what is on disk, exiting
non-zero on drift — so a probe edited without regenerating cannot ship.

The worlds live under tests/ and are therefore exempt from the canonical
lighting recipe (docs/WORLD_RECIPE.md); they are headless and no lane in this
suite renders them.
"""
from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE.parent))

import capabilities as caps  # noqa: E402

WORLDS_DIR = HERE / "worlds"

HEADER = """#VRML_SIM R2025a utf8

# GENERATED by tests/benchmarks/omnibench/lane4/gen_worlds.py -- do not hand-edit.
# OmniBench lane 4a (capability coverage), see tests/benchmarks/omnibench/SPEC.md.
#
# probe : %(id)s
# family: %(family)s
# claim : %(claim)s
%(claim_extra)s
WorldInfo {
  gravity %(gravity)s
  basicTimeStep %(dt)s
  FPS 30
  randomSeed 42
  coordinateSystem "%(coords)s"
  newtonSolver "%(solver)s"
  newtonStatics TRUE
%(world_info)s}
Viewpoint {
  position -6 -6 3
  orientation -0.15 0.05 0.99 1.2
}
Background {
  skyColor [ 0.15 0.17 0.22 ]
}
"""

PROBER = """DEF OMNIBENCH_PROBER Robot {
  translation %(translation)s
  name "omnibench_prober"
  controller "omnibench_prober"
  controllerArgs [
%(args)s  ]
  supervisor TRUE
  children [
%(children)s  ]
%(bounding)s%(physics)s}
"""


def _fmt(x):
    return "%.10g" % x


def _ascii(s):
    """Fold the typographic punctuation the registry's prose uses into ASCII
    before it goes into a .wbt comment. The header declares utf8 and the
    tokenizer copes, but these files are read by editors, diff tools and log
    scrapers on a cp1252 console, and a stray em-dash there has already cost
    this suite a crash."""
    return (s.replace("—", "--").replace("–", "-")
             .replace("’", "'").replace("“", '"')
             .replace("”", '"').replace("…", "...")
             .encode("ascii", "replace").decode("ascii"))


def controller_args(probe, indent="    "):
    args = ["--label=%s" % probe.id,
            "--duration=%s" % _fmt(probe.duration)]
    if probe.measure:
        args.append("--measure=%s" % ";".join(probe.measure))
    if probe.act:
        args.append("--act=%s" % ";".join(probe.act))
    return "".join('%s"%s"\n' % (indent, a) for a in args)


def build(probe):
    """Full .wbt text for one probe."""
    claim_extra = ""
    if probe.doc:
        claim_extra += "# doc   : %s\n" % _ascii(probe.doc)
    if probe.documented_as:
        claim_extra += ("# docs currently claim this is: %s (lane 4 raises a "
                        "finding if the measurement disagrees)\n"
                        % probe.documented_as)
    if probe.kind == caps.KIND_STATIC:
        claim_extra += ("# kind  : STATIC -- this world DECLARES the feature so "
                        "the engine's own\n#         diagnostics can say whether "
                        "it is in the schema at all.\n")
    text = HEADER % {
        "id": probe.id, "family": probe.family, "claim": _ascii(probe.claim),
        "claim_extra": claim_extra,
        "gravity": _fmt(probe.gravity), "dt": _fmt(probe.dt_ms),
        "coords": probe.coordinate_system,
        # Templated rather than hardcoded: `world_info` lines are emitted AFTER
        # this one in the same WorldInfo block, so a probe could not override a
        # hardcoded value by declaring the field again -- the first wins. That
        # is how the cloth probe spent its whole life on a solver that cannot
        # build the SolverVBD a Cloth needs. See Probe.solver.
        "solver": probe.solver,
        "world_info": probe.world_info,
    }
    text += probe.world() if probe.world else ""
    text += PROBER % {
        "translation": probe.prober_translation,
        "args": controller_args(probe),
        "children": probe.prober_children,
        "bounding": probe.prober_bounding,
        "physics": probe.prober_physics,
    }
    return text


def world_path(probe):
    return WORLDS_DIR / ("%s.wbt" % probe.id.replace(".", "_"))


def generate(check=False):
    WORLDS_DIR.mkdir(parents=True, exist_ok=True)
    drift, written = [], 0
    wanted = set()
    for probe in caps.PROBES:
        path = world_path(probe)
        wanted.add(path.name)
        text = build(probe)
        if check:
            old = path.read_text(encoding="utf-8") if path.exists() else None
            if old != text:
                drift.append(probe.id)
            continue
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8", newline="\n")
            written += 1
    # A world left behind by a deleted probe is a world nothing measures.
    # `env_*.wbt` are lane-4b's transient scaling worlds, which must live in
    # this directory so the engine can resolve lane4/controllers/ -- they are
    # owned by run_envelope.py and are not orphans.
    stale = sorted(p.name for p in [*WORLDS_DIR.glob("*.omniworld"), *WORLDS_DIR.glob("*.wbt")]
                   if p.name not in wanted and not p.name.startswith("env_"))
    if not check:
        for name in stale:
            (WORLDS_DIR / name).unlink()
    return written, drift, stale


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true",
                    help="do not write; exit 1 if the worlds on disk differ "
                         "from what the registry produces")
    a = ap.parse_args(argv)
    written, drift, stale = generate(check=a.check)
    if a.check:
        if drift or stale:
            print("lane4 worlds are STALE -- run gen_worlds.py")
            for d in drift:
                print("  drift: %s" % d)
            for s in stale:
                print("  orphan: %s" % s)
            return 1
        print("lane4 worlds up to date (%d probes)" % len(caps.PROBES))
        return 0
    print("lane4: %d probes -> %s (%d written, %d orphans removed)"
          % (len(caps.PROBES), os.path.relpath(WORLDS_DIR), written, len(stale)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
